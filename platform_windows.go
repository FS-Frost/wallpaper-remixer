//go:build windows

package main

import (
	"encoding/binary"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"syscall"
	"unicode/utf16"

	"golang.org/x/sys/windows"
)

const (
	autostartSupported = true
	autostartFileName  = "wallpaper-remixer.vbs"
	stillActive        = 259
)

// pathKey compares paths case-insensitively, like NTFS does.
func pathKey(p string) string {
	return strings.ToLower(filepath.Clean(p))
}

func configureDetached(cmd *exec.Cmd) {
	cmd.SysProcAttr = &syscall.SysProcAttr{
		HideWindow:    true,
		CreationFlags: windows.CREATE_NO_WINDOW | windows.CREATE_NEW_PROCESS_GROUP,
	}
}

func processAlive(pid int) bool {
	handle, err := windows.OpenProcess(windows.PROCESS_QUERY_LIMITED_INFORMATION, false, uint32(pid))
	if err != nil {
		return false
	}
	defer windows.CloseHandle(handle)

	var code uint32
	if err := windows.GetExitCodeProcess(handle, &code); err != nil {
		return false
	}

	return code == stillActive
}

func killProcess(pid int) error {
	p, err := os.FindProcess(pid)
	if err != nil {
		return err
	}

	return p.Kill()
}

func openInDefaultApp(p string) error {
	return exec.Command("rundll32.exe", "url.dll,FileProtocolHandler", p).Start()
}

func revealInFileManager(p string) error {
	cmd := exec.Command("explorer.exe")
	if dirExists(p) {
		cmd.SysProcAttr = &syscall.SysProcAttr{CmdLine: fmt.Sprintf(`explorer.exe "%s"`, p)}
	} else {
		cmd.SysProcAttr = &syscall.SysProcAttr{CmdLine: fmt.Sprintf(`explorer.exe /select,"%s"`, p)}
	}

	// explorer.exe returns a non-zero exit code even on success, so do not wait for it.
	return cmd.Start()
}

func autostartPath() (string, error) {
	appData := os.Getenv("APPDATA")
	if appData == "" {
		return "", fmt.Errorf("APPDATA is not set")
	}

	return filepath.Join(appData, "Microsoft", "Windows", "Start Menu", "Programs", "Startup", autostartFileName), nil
}

// autostartScript builds a VBS that launches exe hidden with -loop.
func autostartScript(exe string) string {
	quoted := strings.ReplaceAll(exe, `"`, `""`)
	dir := strings.ReplaceAll(filepath.Dir(exe), `"`, `""`)

	return strings.Join([]string{
		"' Generated by wallpaper-remixer. Delete this file to disable autostart.",
		`Set shell = CreateObject("WScript.Shell")`,
		fmt.Sprintf(`shell.CurrentDirectory = "%s"`, dir),
		fmt.Sprintf(`shell.Run """%s"" -loop", 0, False`, quoted),
		"",
	}, "\r\n")
}

// encodeUTF16LE encodes text with a BOM, the Unicode format Windows Script Host reads.
func encodeUTF16LE(text string) []byte {
	units := utf16.Encode([]rune(text))
	bs := make([]byte, 2+len(units)*2)
	bs[0], bs[1] = 0xFF, 0xFE
	for i, u := range units {
		binary.LittleEndian.PutUint16(bs[2+i*2:], u)
	}

	return bs
}

func autostartStatus() (enabled bool, scriptPath string, err error) {
	scriptPath, err = autostartPath()
	if err != nil {
		return false, "", err
	}

	return fileExists(scriptPath), scriptPath, nil
}

func enableAutostart() (string, error) {
	logToFile("enable autostart")

	scriptPath, err := autostartPath()
	if err != nil {
		return "", err
	}

	exe, err := os.Executable()
	if err != nil {
		return "", fmt.Errorf("cannot resolve executable: %v", err)
	}

	if err := os.WriteFile(scriptPath, encodeUTF16LE(autostartScript(exe)), 0666); err != nil {
		return "", fmt.Errorf("error writing %q: %v", scriptPath, err)
	}

	return scriptPath, nil
}

func disableAutostart() error {
	logToFile("disable autostart")

	scriptPath, err := autostartPath()
	if err != nil {
		return err
	}

	if err := os.Remove(scriptPath); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("error removing %q: %v", scriptPath, err)
	}

	return nil
}
